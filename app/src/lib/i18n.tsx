const DICTS: Record<Lang, Dict> = { fr, en, es, de, it, pt };

const STORAGE_KEY = "hexgate_lang";

function detectInitial(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    // localStorage indisponible : on retombe sur la langue par défaut.
  }
  return "fr";
}

export type TFunc = (key: string, params?: Record<string, string | number>) => string;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunc;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectInitial);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  // Les overlays sont des fenêtres Tauri séparées, donc des racines React
  // distinctes avec chacune son propre provider : sans cette écoute, changer la
  // langue dans les réglages ne serait appliqué à l'overlay qu'à sa prochaine
  // ouverture. `storage` est émis par les AUTRES fenêtres de la même origine.
  useEffect(() => {
    const onStorage = (e: StorageEvent) => {
      if (e.key !== STORAGE_KEY) return;
      const next = e.newValue as Lang | null;
      if (next && next in DICTS) setLangState(next);
    };
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // pas de persistance possible : le choix reste valable pour la session.
    }
  }, []);

  const t = useCallback<TFunc>(
    (key, params) => {
      const raw = DICTS[lang][key] ?? DICTS.fr[key] ?? key;
      if (!params) return raw;
      return raw.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
    },
    [lang],
  );

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n doit être utilisé dans un <I18nProvider>");
  return ctx;
}
